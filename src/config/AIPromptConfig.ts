/**
 * Отримання промпт конфігурації за доменом
 */
export function getPromptConfig(domain: string, language: 'uk' | 'en' = 'uk'): PromptConfig | null {
  const configKey = `${domain}_${language === 'en' ? 'analysis' : 'analysis'}`;
  return AI_PROMPT_CONFIGS[configKey] || AI_PROMPT_CONFIGS[domain] || AI_PROMPT_CONFIGS['general_analysis'] || null;
}

/**
 * Побудова контекстного промпта
 */
export function buildContextualPrompt(
  domain: string,
  userQuery: string,
  documentContent: string,
  additionalContext?: string,
  language: 'uk' | 'en' = 'uk'
): string {
  const config = getPromptConfig(domain, language);
  if (!config) {
    return userQuery;
  }

  return `
${config.systemPrompt}

📄 ДОКУМЕНТ ДЛЯ АНАЛІЗУ:
${documentContent.substring(0, 3000)}${documentContent.length > 3000 ? '...' : ''}

${additionalContext ? `📋 ДОДАТКОВИЙ КОНТЕКСТ:\n${additionalContext}\n` : ''}

🎯 ЗАПИТ КОРИСТУВАЧА:
${userQuery}

💡 НАДАЙ ВІДПОВІДЬ ВІДПОВІДНО ДО ТВОЄЇ РОЛІ "${config.role}" З УРАХУВАННЯМ СПЕЦИФІКИ ДОМЕНУ "${config.domain.toUpperCase()}":
`;
}

/**
 * Отримання списку доступних доменів
 */
export function getAvailableDomains(): string[] {
  return ['business', 'administrative', 'legal', 'financial', 'general'];
}

/**
 * Перевірка чи підтримується домен
 */
export function isDomainSupported(domain: string): boolean {
  return getAvailableDomains().includes(domain);
}