  /**
   * 🔧 Компіляція промпта з контекстом
   */
  static compilePrompt(template: string, context: PromptContext, data: Record<string, any>): string {
    let prompt = template;
    
    // Заміна контекстних змінних
    if (context.userRole) {
      prompt = prompt.replace(/\{\{userRole\}\}/g, this.translateUserRole(context.userRole));
    }
    if (context.domain) {
      prompt = prompt.replace(/\{\{domain\}\}/g, this.translateDomain(context.domain));
    }
    if (context.urgency) {
      prompt = prompt.replace(/\{\{urgency\}\}/g, this.translateUrgency(context.urgency));
    }
    if (context.previousContext) {
      prompt = prompt.replace(/\{\{previousContext\}\}/g, context.previousContext.join('; '));
    }
    if (context.specialRequirements) {
      prompt = prompt.replace(/\{\{specialRequirements\}\}/g, context.specialRequirements.join('; '));
    }

    // Заміна даних
    for (const [key, value] of Object.entries(data)) {
      const regex = new RegExp(`\\{\\{${key}\\}\\}`, 'g');
      prompt = prompt.replace(regex, String(value));
    }

    return prompt;
  }

  private static translateUserRole(role: string): string {
    const translations = {
      officer: 'офіцер',
      admin: 'адміністратор',
      analyst: 'аналітик',
      commander: 'командир',
      civilian: 'цивільний працівник'
    };
    return translations[role as keyof typeof translations] || role;
  }

  private static translateDomain(domain: string): string {
    const translations = {
      logistics: 'логістика',
      personnel: 'кадри',
      operations: 'операції',
      intelligence: 'розвідка',
      finance: 'фінанси'
    };
    return translations[domain as keyof typeof translations] || domain;
  }

  private static translateUrgency(urgency: string): string {
    const translations = {
      low: 'низька',
      medium: 'середня',
      high: 'висока',
      critical: 'критична'
    };
    return translations[urgency as keyof typeof translations] || urgency;
  }
